def _extract_intents(response: str) -> tuple[str, set[str]]:
    """Strip [INTENT:...] tag from response and return (clean_text, intent_set)."""
    match = _INTENT_RE.search(response)
    if not match:
        return response, set()
    # Remove the tag from wherever it appears in the response
    clean = (response[:match.start()] + response[match.end():]).rstrip()
    tags = {t.strip() for t in match.group(1).split(",") if t.strip()}
    tags.discard("NONE")
    return clean, tags


def _extract_whatsapp_tags(response: str) -> tuple[str, dict[str, str], int | None]:
    """Extract [SLOTS:...] and [READY:N] tags from LLM response.

    Returns (cleaned_response, slots_dict, readiness_score).
    Tolerant to malformed tags — returns empty dict / None instead of raising.

    Supports multiple [SLOTS:...] tags in one response (merged).
    Values containing '=' or ',' are handled conservatively: we take the first
    '=' as separator and only comma-split at the top level.
    """
    slots: dict[str, str] = {}
    ready: int | None = None

    # Extract ALL SLOTS tags (LLM may emit multiple)
    for slots_match in _SLOTS_RE.finditer(response):
        slots_str = slots_match.group(1).strip()
        if not slots_str:
            continue
        for pair in slots_str.split(","):
            pair = pair.strip()
            if "=" not in pair:
                continue
            key, _, val = pair.partition("=")
            key = key.strip().lower()  # Normalize keys to lowercase
            val = val.strip()
            # Normalize malformed double-equals: key==val → val
            val = val.lstrip("=").strip()
            # Reject empty / sentinel / internal values
            if not key or not val:
                continue
            if val.lower() in ("none", "null", "unknown", "n/a", "-"):
                continue
            if key.startswith("_"):
                continue  # Skip LLM attempts to set internal keys
            slots[key] = val

    # Extract READY score (take last occurrence if multiple)
    ready_matches = list(_READY_RE.finditer(response))
    if ready_matches:
        try:
            ready = int(ready_matches[-1].group(1))
            ready = max(0, min(10, ready))
        except (ValueError, TypeError):
            ready = None

    # Strip all tags from response text
    clean = _SLOTS_RE.sub("", response)
    clean = _READY_RE.sub("", clean)
    clean = "\n".join(line for line in clean.split("\n") if line.strip() or line == "")
    clean = clean.strip()

    return clean, slots, ready


def _sanitize_user_message(text: str) -> str:
    """Strip LLM-control tags from user input to prevent prompt injection."""
    if not text:
        return text
    clean = _INTENT_RE.sub("", text)
    clean = _SLOTS_RE.sub("", clean)
    clean = _READY_RE.sub("", clean)
    return clean.strip()


