    async def _safe_retrieve(self, query: str) -> list:
        """Retrieve RAG context; return empty list on any error.

        k=10 instead of default 5 — we want the LLM to have plenty of
        scientific material to quote from directly.
        """
        try:
            docs = await self._rag_service.retrieve(query, k=10)
            logger.debug(f"RAG retrieved {len(docs)} docs for query: {query[:60]!r}")
            return docs
        except Exception as exc:
            logger.error(f"RAG retrieval error: {exc}")
            return []

    def _get_article_context(self, query: str) -> Document | None:
        """If the query mentions a specific article, inject its text as context."""
        if not self._articles:
            return None

        query_lower = query.lower()
        best_article = None
        best_score = 0

        for art in self._articles._articles:
            title_words = [
                w for w in re.split(r"\W+", art.title.lower()) if len(w) >= 4
            ]
            if not title_words:
                continue
            score = sum(1 for w in title_words if w in query_lower)
            if score > best_score:
                best_score = score
                best_article = art

        if best_score < 2:
            return None

        text = best_article.read_text()
        if not text:
            return None

        excerpt = text[:_ARTICLE_INJECT_CHARS]
        logger.debug(
            f"Injecting article context: {best_article.id} (score={best_score})"
        )
        return Document(
            content=excerpt,
            metadata={"source": best_article.filename, "type": "article_injection"},
            score=1.0,
        )

    def _post_process_response(
        self,
        user_message: str,
        response: str,
        conversation: Conversation,
        intents: set[str] | None = None,
    ) -> str:
        """Append contextual content based on LLM-detected intents."""
        result = response
        intents = intents or set()

        # ── Intent-driven appends (PRICE, DETOX, etc.) ───────────────────
        for tag, config in INTENT_TAGS.items():
            if tag not in intents:
                continue
            append_file = config.get("append_file")
            if not append_file:
                continue  # REVIEWS/PURCHASE handled below with URLs
            markers = config.get("already_covered_markers", [])
            lower_result = result.lower()
            already_covered = any(
                m.lower() in lower_result or m in result for m in markers
            )
            if already_covered:
                continue
            append_text = _load_append_text(append_file)
            if append_text:
                result += f"\n\n{append_text}"

        # ── Reviews link ─────────────────────────────────────────────────
        # ALWAYS append the Yandex Disk URL on REVIEWS intent — never skip via
        # already_covered markers (those caused the bot to "promise" reviews
        # without attaching them).
        if "REVIEWS" in intents:
            reviews_url = self._settings.yandex_disk_reviews_url
            if reviews_url and reviews_url not in result:
                result += f"\n\n📹 Видеоотзывы клиентов: {reviews_url}"

        # ── Purchase links ───────────────────────────────────────────────
        if "PURCHASE" in intents:
            kaspi_url = self._settings.kaspi_product_url
            capsules_url = self._settings.kaspi_capsules_url
            whatsapp_url = self._settings.whatsapp_url
            if kaspi_url not in result:
                result += (
                    f"\n\n🛒 *Приобрести Бальзам Возрождение Plus:*"
                    f"\n• Kaspi (рассрочка/кредит): {kaspi_url}"
                    f"\n• Капсулы на Kaspi: {capsules_url}"
                    f"\n• 🏢 Офис: {self._settings.office_address}"
                    f"\n• 💬 WhatsApp-консультация: {whatsapp_url}"
                )

        return result
